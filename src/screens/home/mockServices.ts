export const getServiceNameById = (id?: string): string => {
  if (!id) return 'Salons';
  
  const categoryNames: Record<string, string> = {
    '1': 'Barbing Salons',
    '2': 'Skin & Facial',
    '3': 'Nails Service',
    '4': 'Body & Spa Treatment',
    '5': 'Make-Up & Enhancement',
    '6': 'Hair Removal',
    '7': 'Med Spa & Aesthetic',
    '8': 'Surgical & Cosmetic Surgery',
    '9': 'Wellness & Lifestyle',
    'popular-men': 'Popular Amongst Men',
    'popular-women': 'Popular Amongst Women',
  };
  
  if (categoryNames[id]) {
    return categoryNames[id];
  }

  for (const catServices of Object.values(MOCK_SERVICES_MEN)) {
    const found = catServices.find((s) => s.id === id);
    if (found) return found.name.replace(/\n/g, ' ');
  }

  for (const catServices of Object.values(MOCK_SERVICES_WOMEN)) {
    const found = catServices.find((s) => s.id === id);
    if (found) return found.name.replace(/\n/g, ' ');
  }

  return id.replace(/[-_]/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
};

